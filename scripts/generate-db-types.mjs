#!/usr/bin/env node
/**
 * Generates src/lib/db/types.ts from Supabase CLI when local stack is running,
 * otherwise falls back to committed schema snapshot generation.
 */
import { execSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outPath = path.join(root, "src/lib/db/types.ts");

function trySupabaseGenTypes() {
  try {
    execSync("supabase status --output json", {
      cwd: root,
      stdio: ["ignore", "pipe", "ignore"],
    });
    const output = execSync(
      "supabase gen types typescript --local --schema public",
      { cwd: root, encoding: "utf8" }
    );
    writeFileSync(
      outPath,
      `// Generated by: pnpm db:types\n// Do not edit manually.\n\n${output}`,
      "utf8"
    );
    console.log("Generated types from local Supabase.");
    return true;
  } catch {
    return false;
  }
}

function writeSnapshotTypes() {
  const snapshotPath = path.join(root, "scripts/db-types.snapshot.ts");
  if (!existsSync(snapshotPath)) {
    throw new Error("Missing scripts/db-types.snapshot.ts fallback");
  }
  const body = readFileSync(snapshotPath, "utf8");
  writeFileSync(
    outPath,
    `// Generated by: pnpm db:types (snapshot fallback)\n// Do not edit manually.\n\n${body}`,
    "utf8"
  );
  console.log("Generated types from schema snapshot.");
}

if (!trySupabaseGenTypes()) {
  writeSnapshotTypes();
}
